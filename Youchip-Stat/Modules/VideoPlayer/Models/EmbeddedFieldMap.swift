//  Карта поля, встроенная В САМУ РАЗМЕТКУ как самодостаточные данные (картинка + размеры).
//  Смысл: точка тега хранит только `mapFieldId` (id карты `PlayField`), и без установленной
//  коллекции этот id визуализировать негде. Встроенная карта закрывает пробел — визуализация
//  работает всегда, вся нужная инфа тянется из разметки, а коллекция лишь «идеальный случай».
//
//  Ключ — `id` = `PlayField.id` (глобально уникален), отсюда естественный дедуп: сколько бы тегов
//  ни стояло на одной карте, запись одна. `width/height` берутся у `PlayField` (а НЕ у картинки):
//  позиции штампов лежат в пикселях поля (см. `proceedWithTagAddition`), и для отрисовки их
//  нормализуют именно по этим размерам.
//

import Foundation

struct EmbeddedFieldMap: Codable, Equatable, Identifiable {
    /// = `PlayField.id`.
    let id: String
    var name: String?
    /// Размеры ПОЛЯ (в его собственных единицах), в которых заданы позиции штампов.
    var width: Double
    var height: Double
    /// Сырые байты изображения карты (в JSON кодируются base64).
    var imageData: Data
}
